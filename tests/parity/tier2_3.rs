#![allow(dead_code)]

pub fn assert_f32_slice_close(actual: &[f32], expected: &[f32], epsilon: f32) {
    assert_eq!(
        actual.len(),
        expected.len(),
        "length mismatch: actual={} expected={}",
        actual.len(),
        expected.len()
    );
    for (index, (actual, expected)) in actual.iter().zip(expected.iter()).enumerate() {
        assert!(
            (*actual - *expected).abs() <= epsilon,
            "value mismatch at {index}: actual={actual} expected={expected} epsilon={epsilon}"
        );
    }
}

pub fn assert_u32_slice_eq(actual: &[u32], expected: &[u32]) {
    assert_eq!(
        actual, expected,
        "u32 slice mismatch: actual={actual:?} expected={expected:?}"
    );
}


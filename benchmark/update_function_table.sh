#!/usr/bin/env bash
# Regenerate function-level speed/RSS comparison tables for a small shared set
# of CLIc and clic-rs functions.
#
# Usage:
#   bash benchmark/update_function_table.sh [clic_build_dir]
#
# The C++ side is skipped if the CLIc build directory is unavailable. Build CLIc
# first with CMake, then pass that build directory here.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
BUILD_DIR="${1:-/tmp/clic_build}"
OUT_DIR="$REPO_ROOT/.tmp/function-bench"
CSV_OUT="$REPO_ROOT/benchmark/function_performance.csv"
MD_OUT="$REPO_ROOT/benchmark/function_performance.md"
RUST_BIN="$REPO_ROOT/target/release/examples/parity_bench"
CPP_BIN="$OUT_DIR/clic_bench"

CASES=(
    gaussian_blur
    add_images_weighted
    mean_of_all_pixels
    push_pull
)

mkdir -p "$OUT_DIR"
printf 'implementation,function,size,mean_us,max_rss_kb,status\n' > "$CSV_OUT"

build_rust() {
    (cd "$REPO_ROOT" && cargo build --release --example parity_bench >/dev/null)
}

find_clic_lib() {
    if [[ -f "$BUILD_DIR/clic/libCLIc.so" ]]; then
        printf '%s\n' "$BUILD_DIR/clic/libCLIc.so"
    elif [[ -f "$BUILD_DIR/clic/libCLIc.dylib" ]]; then
        printf '%s\n' "$BUILD_DIR/clic/libCLIc.dylib"
    fi
}

build_cpp() {
    local clic_lib
    clic_lib="$(find_clic_lib || true)"
    if [[ -z "$clic_lib" ]]; then
        return 1
    fi

    local opencl_flags=()
    if [[ "$(uname -s)" == "Darwin" ]]; then
        opencl_flags=(-framework OpenCL)
    else
        opencl_flags=(-lOpenCL)
    fi

    c++ -std=c++17 -O2 \
        -I"$REPO_ROOT/CLIc/clic/include" \
        -I"$BUILD_DIR/clic/include" \
        -I"$BUILD_DIR/_deps/eigen-src" \
        -I"$BUILD_DIR/_deps/clekernels-src/kernels" \
        -I"$BUILD_DIR/_deps/vkfft-src/vkFFT" \
        "$SCRIPT_DIR/clic_bench.cpp" \
        -L"$BUILD_DIR/clic" -lCLIc \
        -Wl,-rpath,"$BUILD_DIR/clic" \
        "${opencl_flags[@]}" \
        -o "$CPP_BIN"
}

append_failure() {
    local implementation="$1"
    local function="$2"
    local status="$3"
    printf '%s,%s,,,,%s\n' "$implementation" "$function" "$status" >> "$CSV_OUT"
}

run_case() {
    local implementation="$1"
    local bin="$2"
    local function="$3"
    local stdout_file="$OUT_DIR/${implementation}_${function}.out"
    local stderr_file="$OUT_DIR/${implementation}_${function}.err"
    local time_file="$OUT_DIR/${implementation}_${function}.time"

    set +e
    /usr/bin/time -f 'RSS_KB %M' -o "$time_file" "$bin" "$function" \
        >"$stdout_file" 2>"$stderr_file"
    local status=$?
    set -e

    if [[ "$status" -ne 0 ]]; then
        append_failure "$implementation" "$function" "failed"
        return
    fi

    local rss_kb
    rss_kb="$(awk '/^RSS_KB / { print $2 }' "$time_file")"
    awk -v implementation="$implementation" -v rss_kb="$rss_kb" '
        /^RESULT / {
            printf "%s,%s,%s,%s,%s,ok\n", implementation, $2, $3, $4, rss_kb
        }
    ' "$stdout_file" >> "$CSV_OUT"
}

write_markdown() {
    {
        echo "# Function Performance"
        echo
        echo "Generated by \`bash benchmark/update_function_table.sh [clic_build_dir]\`."
        echo "Each function runs in its own process; RSS is the process maximum reported by \`/usr/bin/time\`."
        echo
        echo "| Implementation | Function | Size | Mean us | Max RSS KB | Status |"
        echo "|---|---|---:|---:|---:|---|"
        awk -F, 'NR > 1 {
            printf "| `%s` | `%s` | %s | %s | %s | %s |\n", $1, $2, ($3 == "" ? "-" : $3), ($4 == "" ? "-" : $4), ($5 == "" ? "-" : $5), $6
        }' "$CSV_OUT"
    } > "$MD_OUT"
}

echo "Building Rust benchmark example..."
build_rust

cpp_available=0
if build_cpp; then
    cpp_available=1
else
    echo "Skipping C++ benchmark: CLIc library not found under $BUILD_DIR" >&2
fi

for function in "${CASES[@]}"; do
    if [[ "$cpp_available" -eq 1 ]]; then
        run_case cpp "$CPP_BIN" "$function"
    else
        append_failure cpp "$function" "missing-clic-build"
    fi
    run_case rust "$RUST_BIN" "$function"
done

write_markdown
echo "Wrote $CSV_OUT"
echo "Wrote $MD_OUT"
